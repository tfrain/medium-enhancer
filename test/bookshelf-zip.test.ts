import assert from 'node:assert/strict'
import { crc32, encodeZip } from '../src/shared/zip.ts'
const encoder = new TextEncoder()
assert.equal(crc32(encoder.encode('')), 0)
assert.equal(crc32(encoder.encode('123456789')), 0xcbf43926)
assert.equal(crc32(encoder.encode('The quick brown fox jumps over the lazy dog')), 0x414fa339)
const bytes = encodeZip([{ name: '图书.md', data: encoder.encode('hello') }, { name: 'two.md', data: encoder.encode('world') }])
const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
assert.equal(view.getUint32(0, true), 0x04034b50)
assert.equal(view.getUint16(6, true), 0x800, 'UTF-8 filename flag')
assert.equal(view.getUint16(8, true), 0, 'store only')
assert.equal(view.getUint32(14, true), 0x3610a686)
assert.equal(view.getUint32(18, true), 5)
const nameLength = view.getUint16(26, true)
assert.equal(new TextDecoder().decode(bytes.slice(30, 30 + nameLength)), '图书.md')
assert.equal(new TextDecoder().decode(bytes.slice(30 + nameLength, 35 + nameLength)), 'hello')
const end = bytes.length - 22
assert.equal(view.getUint32(end, true), 0x06054b50)
assert.equal(view.getUint16(end + 10, true), 2)
const central = view.getUint32(end + 16, true)
assert.equal(view.getUint32(central, true), 0x02014b50)
assert.equal(view.getUint32(central + 42, true), 0)
assert.equal(encodeZip([]).length, 22)
assert.throws(() => encodeZip([{ name: '../escape.md', data: new Uint8Array() }]), /filename/i)
assert.throws(() => encodeZip([{ name: 'same.md', data: new Uint8Array() }, { name: 'SAME.md', data: new Uint8Array() }]), /duplicate/i)
console.log('PASS ZIP CRC32 known vectors, UTF-8, store headers, directory offsets and unsafe names')
