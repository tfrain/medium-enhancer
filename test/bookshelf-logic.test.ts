import assert from 'node:assert/strict'
import { loadSource } from './load-source.ts'

const { normalizeItem, archiveItem, normalizeHighlight, requireBookshelfPro } = loadSource('src/shared/bookshelf-model.ts', {})
const { createSearchIndex, searchBookshelf } = loadSource('src/shared/bookshelf-search.ts', {})
const { exportMarkdown, exportFiles } = loadSource('src/shared/bookshelf-export.ts', {})
const url = 'https://medium.com/@writer/story-abcdef123456?source=test#abcd'
const metadata = { url, canonicalUrl: 'https://medium.com/p/abcdef123456?source=x', title: '  A title  ', author: ' Writer ', publication: 'Pub', subtitle: 'Sub' }
const item = normalizeItem(metadata, undefined, 100)
assert.equal(item.key, 'abcdef123456')
assert.equal(item.url, 'https://medium.com/p/abcdef123456')
assert.equal(item.title, 'A title')
assert.equal(item.savedAt, 100)
assert.equal(item.readAt, null)
assert.deepEqual(Array.from(item.tags), [])
const archived = archiveItem({ ...item, tags: ['local'], readAt: 150 }, 'Body with searchable quokkas.', true, 200)
assert.equal(archived.wordCount, 4)
const resaved = normalizeItem({ ...metadata, title: 'Updated', canonicalUrl: 'https://example.com/evil' }, archived, 300)
assert.equal(resaved.title, 'Updated')
assert.equal(resaved.savedAt, 100)
assert.equal(resaved.readAt, 150)
assert.equal(resaved.tags[0], 'local')
assert.equal(resaved.markdown, archived.markdown)
assert.equal(resaved.url, 'https://medium.com/@writer/story-abcdef123456')
assert.throws(() => normalizeItem({ ...metadata, url: 'https://medium.com/@writer' }), /story/i)
assert.throws(() => archiveItem(item, 'secret', false), /Pro/)
assert.throws(() => normalizeHighlight(item.key, { text: 'secret' }, false), /Pro/)
assert.throws(() => requireBookshelfPro(false), /Pro/)
assert.throws(() => archiveItem(item, '  ', true), /empty/i)
const highlight = normalizeHighlight(item.key, { text: '  Useful\n selection ', paragraphId: 'abcd', note: 'remember wombats' }, true, 250)
assert.equal(highlight.text, 'Useful selection')
assert.equal(highlight.paragraphId, 'abcd')
assert.equal(normalizeHighlight(item.key, { text: 'text', paragraphId: 'bad-id' }, true).paragraphId, '')
assert.throws(() => normalizeHighlight(item.key, { text: ' ' }, true), /select/i)
const index = createSearchIndex([archived], [highlight])
assert.equal(searchBookshelf(index, 'QUOKKAS', true)[0].item.key, item.key)
assert.match(searchBookshelf(index, 'wombats', true)[0].snippet, /remember wombats/)
assert.equal(searchBookshelf(index, 'writer quokkas', true).length, 1)
assert.equal(searchBookshelf(index, 'unknown', true).length, 0)
assert.throws(() => searchBookshelf(index, 'quokkas', false), /Pro/)
assert.throws(() => exportMarkdown(item, [], false), /Pro/)
assert.throws(() => exportFiles([item], [], false), /Pro/)
const special = { ...archived, title: 'Title: "quoted"\nnew line', author: 'Back\\slash', tags: ['a:b', 'two\nlines'] }
const md = exportMarkdown(special, [highlight], true)
assert.ok(md.includes('title: "Title: \\"quoted\\"\\nnew line"'.replaceAll('\\\\"', '\\"')))
assert.ok(md.includes('author: "Back\\\\slash"'))
assert.ok(md.includes('tags: ["a:b","two\\nlines"]'))
assert.ok(md.includes('> - Useful selection'))
assert.ok(md.includes('remember wombats'))
assert.ok(md.indexOf('> -') < md.indexOf('Body with searchable quokkas.'))
const names = exportFiles(['../CON', '../con', 'a/b:*?', 'A/B:*?', '...', '图书'].map((title, i) => ({ ...item, title, key: String(i) })), [], true).map((f: any) => f.name)
assert.equal(new Set(names.map((n: string) => n.toLowerCase())).size, 6)
assert.ok(names.every((n: string) => !/[\\/:*?"<>|]/.test(n) && !n.startsWith('.')))
assert.ok(names.includes('图书.md'))
assert.ok(!names.some((n: string) => /^con\.md$/i.test(n)))
const unicodeFiles = exportFiles(['书'.repeat(100), '书'.repeat(100)].map((title, i) => ({ ...item, title, key: String(i) })), [], true)
assert.ok(unicodeFiles.every((file: any) => Buffer.byteLength(file.name, 'utf8') <= 240), 'portable UTF-8 filename byte budget includes suffix')
const big = createSearchIndex(Array.from({ length: 1000 }, (_, i) => ({ ...archived, key: String(i), markdown: 'ordinary words '.repeat(300) + 'needle' })), [])
const start = performance.now()
assert.equal(searchBookshelf(big, 'needle', true).length, 1000)
assert.ok(performance.now() - start < 1500, 'pre-indexed 1,000-item search stays responsive')
console.log('PASS Bookshelf normalization, dedupe, archive/highlight/search/export Pro gates, search and portable Markdown')
